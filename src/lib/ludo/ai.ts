/* Sweet AI move choice for local 1-player games. Three difficulty
   levels, all choosing only from the engine's legal moves — the AI
   can never make an illegal move, and the dice stays fair (the roll
   is generated by the caller, never by the AI).

   - Easy: a uniformly random legal move.
   - Medium: basic strategy — captures, leaving base, reaching home,
     home-column safety and safe squares, plus a progression
     tiebreak. No threat analysis, no blockade play.
   - Hard: the full heuristic (botMove): captures, blockades, threat
     escape/avoidance, home-column safety and progression.

   `rand` is injectable so tests can drive Easy deterministically. */

import { botMove, effectiveSafeCells, legalMoves, resolveRules, trackIndex, type LudoState } from "./engine";
import type { AiDifficulty } from "./settings";

export function chooseAiMove(
  state: LudoState,
  roll: number,
  difficulty: AiDifficulty,
  rand: () => number = Math.random,
): number | null {
  const legal: number[] = legalMoves(state, roll);
  if (legal.length === 0) {
    return null;
  }
  if (difficulty === "easy") {
    return legal[Math.floor(rand() * legal.length)];
  }
  if (difficulty === "hard") {
    return botMove(state, roll);
  }
  return mediumMove(state, roll, legal);
}

function mediumMove(state: LudoState, roll: number, legal: number[]): number | null {
  const safeCells = effectiveSafeCells(resolveRules(state));
  const player = state.players[state.turn];
  let bestToken: number | null = null;
  let bestScore = 0;
  let first = true;
  for (const tokenIndex of legal) {
    const progress = player.tokens[tokenIndex];
    const dest = progress === -1 ? 0 : progress + roll;
    let score = 0;
    const destCell = trackIndex(player.color, dest);
    /* Capture. */
    if (destCell !== null && safeCells.indexOf(destCell) === -1) {
      for (let p = 0; p < state.players.length; p++) {
        if (p === state.turn) continue;
        const opp = state.players[p];
        for (let t = 0; t < opp.tokens.length; t++) {
          if (trackIndex(opp.color, opp.tokens[t]) === destCell) {
            score += 100;
          }
        }
      }
    }
    /* Leave base. */
    if (progress === -1) {
      score += 80;
    }
    /* Reach the centre. */
    if (dest === 57) {
      score += 70;
    }
    /* Enter the safety of the home column. */
    if (dest >= 51 && dest <= 56) {
      score += 25;
    }
    /* Land on a safe square. */
    if (destCell !== null && safeCells.indexOf(destCell) !== -1) {
      score += 12;
    }
    /* Prefer the furthest-advanced token as a tiebreak. */
    score += dest * 0.5;
    if (first || score > bestScore) {
      bestScore = score;
      bestToken = tokenIndex;
      first = false;
    }
  }
  return bestToken;
}
