import type { ArrowSpec } from "./solver";
import { parseLevel, type MazeArrow } from "./solver";

export type ArrowsDifficulty = "normal" | "hard" | "superHard";

export interface ArrowsLevel {
  /** 1-based level number. */
  n: number;
  /** Square grid size (size x size cells). */
  size: number;
  /** Winding arrows: tail cell + step letters (U/D/L/R), tail to head. */
  arrows: ArrowSpec[];
}

/** Difficulty bands, like the reference game: Normal 1-10, Hard
    11-20, Super Hard 21-30. */
export function levelDifficulty(n: number): ArrowsDifficulty {
  if (n <= 10) return "normal";
  if (n <= 20) return "hard";
  return "superHard";
}

